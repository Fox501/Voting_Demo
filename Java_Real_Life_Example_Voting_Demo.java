// What are the requirements?                                       *
//		We will create a Java program that will implement the       *
//      greater than or equal comparison operator (>=) to find out  *
//      if variable myAge is greater than or equal to minimum       *
//      voting age. We will also implement a second comparison      *
//      operator, less than (<) where compare myAge to the maximum  *
//      non-voting age.                                             *
//*******************************************************************


public class Java_Real_Life_Example_Voting_Demo
{
	public static void main(String[] args)
	{
		int myAge = 18;
		
		
		//This will output true, myAge is old enough to vote.
		System.out.println(myAge >= 18);
		
		//This will output false, myAge is old enough to vote
		System.out.println(myAge < 18);

    }//End of method main.
	
}//End of class Java_Real_Life_Example_Voting_Demo.

